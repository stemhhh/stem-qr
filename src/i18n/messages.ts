export const messages: Record<Locale, Record<MessageKey, string>> = { es, en, pt, fr }

export function formatMessage(
  template: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined ? `{${key}}` : String(vars[key]),
  )
}

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem('stem-qr-locale')
      ?? localStorage.getItem('estudio-qr-locale')
    if (saved === 'es' || saved === 'en' || saved === 'pt' || saved === 'fr') return saved
  } catch {
    /* ignore */
  }
  const lang = navigator.language?.toLowerCase() ?? 'es'
  if (lang.startsWith('en')) return 'en'
  if (lang.startsWith('pt')) return 'pt'
  if (lang.startsWith('fr')) return 'fr'
  return 'es'
}
